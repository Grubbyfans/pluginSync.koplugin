import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createServer, loadConfig } from '../src/server.js';
import { validId, list, packagePlugin } from '../src/scanner.js';
import { crc32 } from '../src/zip.js';

test('ID and CRC validation', () => {
  assert.equal(crc32(Buffer.from('123456789')), 0xcbf43926);
  for (const id of ['../a.koplugin','a/evil.koplugin','a..b.koplugin','a\\b.koplugin','a.koplugin/']) assert.equal(validId(id),false);
  assert.equal(validId('my-plugin.koplugin'),true);
});
test('existing configs enable discovery by default and can explicitly disable it', async t => {
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'pluginsync-config-'));
  t.after(()=>fs.rm(root,{recursive:true,force:true}));
  const file=path.join(root,'config.json');
  await fs.writeFile(file,JSON.stringify({pluginRoot:root}));
  assert.equal((await loadConfig(file)).discovery,true);
  await fs.writeFile(file,JSON.stringify({pluginRoot:root,discovery:false}));
  assert.equal((await loadConfig(file)).discovery,false);
  await fs.writeFile(file,JSON.stringify({pluginRoot:root,discovery:'yes'}));
  await assert.rejects(loadConfig(file),/discovery must/);
});
test('list, download, limits, changed files, and HTTP errors', async t => {
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'pluginsync-'));
  t.after(() => fs.rm(root,{recursive:true,force:true}));
  const dir=path.join(root,'demo.koplugin'); await fs.mkdir(dir);
  await fs.writeFile(path.join(dir,'main.lua'),'return {}');
  await fs.writeFile(path.join(dir,'_meta.lua'),'return {version="1.2.0"}');
  await fs.mkdir(path.join(dir,'.git')); await fs.writeFile(path.join(dir,'.git','config'),'secret');
  await fs.writeFile(path.join(root,'versions.json'),'{"demo.koplugin":"2.0.0"}');
  await fs.mkdir(path.join(root,'bad.koplugin')); await fs.writeFile(path.join(root,'bad.koplugin','pluginsync.json'),'{');
  const config={pluginRoot:root,maxFiles:5000,maxBytes:50*1024*1024,exclude:['.git'],token:'test'};
  const listing=await list(config);
  assert.equal(listing.plugins.length,1); assert.equal(listing.errors.length,1);
  assert.equal(listing.plugins[0].version,'2.0.0');
  let pkg=await packagePlugin(config,'demo.koplugin');
  assert.equal(pkg.version,'2.0.0'); assert.equal(pkg.data.includes(Buffer.from('secret')),false);
  await fs.writeFile(path.join(dir,'pluginsync.json'),'{"version":"3.0.0"}');
  await fs.writeFile(path.join(dir,'main.lua'),'return {changed=true}');
  const changed=await packagePlugin(config,'demo.koplugin');
  assert.equal(changed.version,'3.0.0'); assert.notDeepEqual(pkg.data,changed.data);
  await assert.rejects(packagePlugin({...config,maxBytes:1},'demo.koplugin'),/limits/);
  await assert.rejects(packagePlugin({...config,maxFiles:1},'demo.koplugin'),/limits/);
  await assert.rejects(packagePlugin(config,'..evil.koplugin'),/Invalid/);
  const server=createServer(config); await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  t.after(()=>new Promise(resolve=>server.close(resolve)));
  const base=`http://127.0.0.1:${server.address().port}`;
  assert.equal((await fetch(base+'/api/health')).status,401);
  const discovery=await (await fetch(base+'/api/discovery')).json();
  assert.equal(discovery.discoveryVersion,1);
  assert.equal(discovery.service,'koreader-plugin-sync');
  assert.equal(discovery.authRequired,true);
  assert.deepEqual(Object.keys(discovery).sort(),['service','apiVersion','discoveryVersion','name','authRequired'].sort());
  assert.equal((await fetch(base+'/api/plugins')).status,401);
  const headers={Authorization:'Bearer test'};
  assert.equal((await (await fetch(base+'/api/health',{headers})).json()).ok,true);
  assert.equal((await fetch(base+'/api/plugins/demo.koplugin/download',{headers})).headers.get('x-plugin-version'),'3.0.0');
  assert.equal((await fetch(base+'/api/plugins/missing.koplugin/download',{headers})).status,404);
  assert.equal((await fetch(base+'/api/plugins/%2e%2efoo.koplugin/download',{headers})).status,400);
  assert.equal((await fetch(base+'/api/health',{headers,method:'POST'})).status,405);
  assert.equal((await fetch(base+'/api/nope',{headers})).status,404);
});
